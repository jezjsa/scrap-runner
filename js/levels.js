export const COLS = 32;
export const ROWS = 18;

function isKeep(ch) {
  return "SHCBRDXUWGMKPo><E".includes(ch);
}

function isLadderChar(ch) {
  return ch === "L" || ch === "+";
}

function connectLaddersToFloor(grid) {
  const cells = grid.map((row) => row.split(""));
  const floorY = ROWS - 1;
  let firstLedge = -1;
  for (let y = floorY - 1; y >= 0; y -= 1) {
    if (cells[y].some((ch) => ch === "=" || ch === "+")) {
      firstLedge = y;
      break;
    }
  }
  if (firstLedge < 0) return grid;
  for (let x = 0; x < COLS; x += 1) {
    const onLedge = isLadderChar(cells[firstLedge][x]);
    const aboveLedge = firstLedge > 0 && isLadderChar(cells[firstLedge - 1][x]);
    if (!onLedge && !aboveLedge) continue;
    for (let y = firstLedge; y < floorY; y += 1) {
      const ch = cells[y][x];
      if (ch === "=") cells[y][x] = "+";
      else if (ch === "." || ch === " ") cells[y][x] = "L";
      else if (isKeep(ch)) break;
    }
  }
  return cells.map((row) => row.join(""));
}

function punchLaddersThroughLedges(grid) {
  const cells = grid.map((row) => row.split(""));
  for (let x = 0; x < COLS; x += 1) {
    for (let y = 1; y < ROWS; y += 1) {
      if (!isLadderChar(cells[y][x])) continue;
      if (cells[y - 1][x] === "=") cells[y - 1][x] = "+";
    }
  }
  return cells.map((row) => row.join(""));
}

function pack(name, blurb, raw) {
  const rows = raw.replace(/^\n/, "").replace(/\n$/, "").split("\n");
  if (rows.length !== ROWS) {
    throw new Error(`${name}: expected ${ROWS} rows, got ${rows.length}`);
  }
  const grid = rows.map((row) => {
    const line = row.length >= COLS ? row.slice(0, COLS) : row.padEnd(COLS, ".");
    if (line.length !== COLS) throw new Error(`${name}: bad row ${line}`);
    return line;
  });
  return { name, blurb, grid: punchLaddersThroughLedges(connectLaddersToFloor(grid)) };
}

