export const COLS = 32;
export const ROWS = 18;

/** First row a walkable ledge may sit on. Row 4 leaves room for the 60px sprite plus a 56px jump. */
export const MIN_WALK_ROW = 4;

const WALK_CHARS = "=+><EMK";

function isKeep(ch) {
  return "SHCBRDXUWGMKPo><EFT".includes(ch);
}

function isLadderChar(ch) {
  return ch === "L" || ch === "+";
}

function connectLaddersToFloor(grid, onlyCols) {
  const cells = grid.map((row) => row.split(""));
  const floorY = ROWS - 1;
  let firstLedge = -1;
  for (let y = floorY - 1; y >= 0; y -= 1) {
    if (cells[y].some((ch) => ch === "=" || ch === "+")) {
      firstLedge = y;
      break;
    }
  }
  if (firstLedge < 0) return grid;
  for (let x = 0; x < COLS; x += 1) {
    if (onlyCols && !onlyCols.includes(x)) continue;
    const onLedge = isLadderChar(cells[firstLedge][x]);
    const aboveLedge = firstLedge > 0 && isLadderChar(cells[firstLedge - 1][x]);
    if (!onLedge && !aboveLedge) continue;
    for (let y = firstLedge; y < floorY; y += 1) {
      const ch = cells[y][x];
      if (ch === "=") cells[y][x] = "+";
      else if (ch === "." || ch === " ") cells[y][x] = "L";
      else if (isKeep(ch)) break;
    }
  }
  return cells.map((row) => row.join(""));
}

function punchLaddersThroughLedges(grid) {
  const cells = grid.map((row) => row.split(""));
  for (let x = 0; x < COLS; x += 1) {
    for (let y = 1; y < ROWS; y += 1) {
      if (!isLadderChar(cells[y][x])) continue;
      if (cells[y - 1][x] === "=") cells[y - 1][x] = "+";
    }
  }
  return cells.map((row) => row.join(""));
}

function clearOrphanLedges(grid) {
  const realFloor = "=><E";
  return grid.map((row) => {
    const cells = row.split("");
    for (let x = 0; x < cells.length; x += 1) {
      if (cells[x] !== "+") continue;
      const left = x > 0 && realFloor.includes(cells[x - 1]);
      const right = x < cells.length - 1 && realFloor.includes(cells[x + 1]);
      if (!left && !right) cells[x] = "L";
    }
    return cells.join("");
  });
}

function isWalkRow(row) {
  return row.split("").some((ch) => WALK_CHARS.includes(ch));
}

function highestWalkRow(grid) {
  return grid.findIndex((row) => isWalkRow(row));
}

function rowIsSpacer(row) {
  return row.split("").every((ch) => ch === "." || ch === " " || ch === "L");
}

function rowIsAir(row) {
  return row.split("").every((ch) => ch === "." || ch === " ");
}

function findSpacerRow(grid, afterY) {
  const floorY = ROWS - 1;
  const air = [];
  const ladder = [];
  for (let y = afterY; y < floorY - 1; y += 1) {
    const row = grid[y];
    if (row.includes("S") || row.includes("H")) continue;
    if (!rowIsSpacer(row)) continue;
    if (rowIsAir(row)) air.push(y);
    else ladder.push(y);
  }
  return air[0] ?? ladder[0] ?? -1;
}

function ensureHeadroom(grid, name) {
  const next = grid.slice();
  let guard = 0;
  while (guard < 8) {
    const top = highestWalkRow(next);
    if (top < 0 || top >= MIN_WALK_ROW) break;
    const removeAt = findSpacerRow(next, top + 2);
    if (removeAt < 0) {
      throw new Error(`${name}: no spare row to drop ledges to row ${MIN_WALK_ROW}`);
    }
    next.splice(removeAt, 1);
    next.unshift(".".repeat(COLS));
    guard += 1;
  }
  const top = highestWalkRow(next);
  if (top >= 0 && top < MIN_WALK_ROW) {
    throw new Error(`${name}: walkable ledge on row ${top}, need row ${MIN_WALK_ROW}+`);
  }
  return next;
}

function pack(name, blurb, raw, opts = {}) {
  const rows = raw.replace(/^\n/, "").replace(/\n$/, "").split("\n");
  if (rows.length !== ROWS) {
    throw new Error(`${name}: expected ${ROWS} rows, got ${rows.length}`);
  }
  const grid = rows.map((row) => {
    const line = row.length >= COLS ? row.slice(0, COLS) : row.padEnd(COLS, ".");
    if (line.length !== COLS) throw new Error(`${name}: bad row ${line}`);
    return line;
  });
  return {
    name,
    blurb,
    grid: clearOrphanLedges(punchLaddersThroughLedges(connectLaddersToFloor(ensureHeadroom(grid, name), opts.floorLadderCols))),
  };
}

